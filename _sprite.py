def pattern_to_svg(pat):
    rows = [r for r in pat.strip('\n').split('\n') if r.strip()]
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == '#':
                w = 1
                while x + w < len(row) and row[x + w] == '#':
                    w += 1
                out.append('<rect x="%d" y="%d" width="%d" height="1"/>' % (x, y, w))
                x += w
            else:
                x += 1
    return ''.join(out)


def build_sprite():
    parts = ['<svg class="sprite" width="0" height="0" aria-hidden="true" focusable="false" '
             'style="position:absolute;pointer-events:none">']
    parts.append('  <symbol id="bg-logo" viewBox="%s"><path transform="%s" d="%s" fill="currentColor"/></symbol>'
                 % (LOGO_VB, LOGO_TR, LOGO_D))
    for name, pat in P.items():
        parts.append('  <symbol id="i-%s" viewBox="0 0 16 16" shape-rendering="crispEdges">'
                     '<g fill="currentColor">%s</g></symbol>' % (name, pattern_to_svg(pat)))
    parts.append('</svg>')
    return "\n".join(parts)


