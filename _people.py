def esc(t):
    return t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def card(p, kind):
    facts = ''.join('<i>%s</i>' % esc(f) for f in p['facts'])
    return (
      '      <button class="pcard rv" type="button" data-bio="bio-%s">\n'
      '        <span class="pcard-ph"><img src="assets/people/%s" alt="%s" loading="lazy" '
      'width="%d" height="%d"%s></span>\n'
      '        <span class="pcard-body">\n'
      '          <span class="pcard-tag">%s</span>\n'
      '          <span class="pcard-nm">%s</span>\n'
      '          <span class="pcard-rl">%s</span>\n'
      '          <span class="pcard-facts">%s</span>\n'
      '          <span class="pcard-more">Читати профіль</span>\n'
      '        </span>\n'
      '      </button>'
      % (p['id'], p['photo'], esc(p['name']),
         1200 if kind == 'partner' else 900,
         750 if kind == 'partner' else 1125,
         ' class="is-logo"' if kind == 'partner' else '',
         esc(p['tag']), esc(p['name']), esc(p['role']), facts))


def bio(p):
    out = ['  <div class="bio-src" id="bio-%s" hidden>' % p['id']]
    out.append('    <span class="bio-tag">%s</span>' % esc(p['tag']))
    out.append('    <h3 class="bio-nm">%s</h3>' % esc(p['name']))
    out.append('    <p class="bio-rl">%s</p>' % esc(p['role']))
    out.append('    <p class="bio-lead">%s</p>' % esc(p['lead']))
    if p['bullets']:
        out.append('    <ul class="bio-list">%s</ul>'
                   % ''.join('<li>%s</li>' % esc(b) for b in p['bullets']))
    if p['quote']:
        out.append('    <blockquote class="bio-q">%s</blockquote>' % esc(p['quote']))
    if p['tail']:
        out.append('    <p class="bio-tail">%s</p>' % esc(p['tail']))
    if p['ig']:
        out.append('    <a class="bio-ig" href="https://instagram.com/%s" target="_blank" '
                   'rel="noopener">@%s</a>' % (p['ig'], p['ig']))
    out.append('  </div>')
    return '\n'.join(out)


