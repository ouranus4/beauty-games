def build():
    cards = '\n'.join(card(p, 'person') for p in PEOPLE)
    logos = '\n'.join(card(p, 'partner') for p in PARTNERS)
    bios = '\n'.join(bio(p) for p in PEOPLE + PARTNERS)
    return PEOPLE_BLOCK % (cards, logos, bios)


